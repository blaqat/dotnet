/* ============================================================
   kit/theme.js · i8 · DK · the theme: ?theme=light (default) | dark | auto (follows prefers-color-scheme)
   kit/yarn.js includes it synchronously, right after itself, so <html data-theme> and the dark stylesheets are in
   place before the first paint (no flash of light). Pages that load yarn.js deferred (review.html, the gallery)
   include it directly in <head> instead. Light loads nothing and changes nothing.

   <html data-theme="light|dark">   the theme in force (auto resolves it, and follows the OS while the page is open)
   <html data-theme-auto>          set while ?theme=auto
   Dark loads, in order:
     kit/dark/<name>.gen.css   right after each themed stylesheet (and after the components page's / gallery's <style>
                               and the player's #yp-css): its colour rules copied for dark with zero added
                               specificity, so the dark cascade is the light one. Generated by _tools/dark-gen.mjs.
     kit/dark.css              the hand-made layer: the dark tokens + tuning (html[data-theme="dark"] …), last.
   While a theme other than light is on, a same-site link keeps ?theme (plain links, the nav, the section cloth).
   window.YarnTheme = { mode, current, set(mode) → Promise, after(el, name) }; window "yarntheme" fires on a change.
   ============================================================ */
(() => {
  "use strict";
  if (window.YarnTheme) return;
  const SCRIPT = document.currentScript;
  const KIT = (SCRIPT && SCRIPT.src) || new URL("kit/theme.js", location.href).href;
  const ROOT = new URL("../", KIT).href;
  const html = document.documentElement;
  const VALUES = ["light", "dark", "auto"];
  const SYNC = !!SCRIPT && !SCRIPT.defer && !SCRIPT.async && document.readyState === "loading";
  let v = new URLSearchParams(location.search).get("theme");
  if (!VALUES.includes(v) && !/[?&]embed=/.test(location.search)) {
    // the saved ⚙ choice (yarn.js also merges it into the URL; a deferred yarn.js does that too late for the first paint)
    for (const s of ["localStorage", "sessionStorage"]) {
      try { const raw = window[s].getItem("yarn.review.i8"); v = (((raw && JSON.parse(raw).choices) || {}).kit || {}).theme?.v; break; } catch (_) {}
    }
  }
  let mode = VALUES.includes(v) ? v : "light";
  const mq = matchMedia("(prefers-color-scheme: dark)");
  const resolve = () => (mode === "auto" ? (mq.matches ? "dark" : "light") : mode);
  const apply = () => {
    const was = html.dataset.theme;
    html.dataset.theme = resolve();
    mode === "auto" ? (html.dataset.themeAuto = "") : delete html.dataset.themeAuto;
    if (was && was !== html.dataset.theme) dispatchEvent(new CustomEvent("yarntheme", { detail: { mode, theme: html.dataset.theme } }));
  };

  // themed stylesheets (path from the mocks' root) → their generated dark copy
  const GEN = { "kit/yarn.css": "yarn", "kit/bg/jersey.css": "jersey", "home/home.css": "home", "projects/projects.css": "projects",
    "music/music.css": "music", "thoughts/stitched.css": "stitched", "thoughts/tier.css": "tier", "studio/studio.css": "studio",
    "review/roundup.css": "roundup" };
  // pages whose own <style> is themed
  const INLINE = { "kit/components.html": "components", "index.html": "index", "": "index" };
  const rel = (href) => (href && href.startsWith(ROOT) ? href.slice(ROOT.length).split(/[?#]/)[0] : null);
  let loaded = false;
  const pending = [];
  const mk = (href, name) => {
    const l = document.createElement("link");
    l.rel = "stylesheet"; l.href = href; l.dataset.ydark = name; l.setAttribute("blocking", "render");
    pending.push(new Promise((res) => { l.onload = l.onerror = res; }));
    return l;
  };
  function after(el, name) {
    if (!loaded || !el || !el.parentNode) return null;
    const nx = el.nextElementSibling;
    if (nx && nx.dataset && nx.dataset.ydark === name) return nx;
    const l = mk(new URL(`dark/${name}.gen.css`, KIT).href, name);
    el.after(l);
    return l;
  }
  const inl = INLINE[rel(location.href)];
  const companion = (el) => {
    if (el.tagName === "LINK" && el.rel === "stylesheet") { const n = GEN[rel(el.href)]; if (n) after(el, n); }
    else if (el.tagName === "STYLE") { if (el.id === "yp-css") after(el, "player"); else if (inl && el === document.querySelector("style:not(#yp-css)")) after(el, inl); }
  };
  function load({ write = false } = {}) {
    if (loaded) return Promise.all(pending);
    loaded = true;
    document.querySelectorAll('link[rel="stylesheet"], style').forEach(companion);
    // sheets that arrive later (a page's <style> after kit/yarn.js, the background a deferred yarn.js adds, the
    // player's #yp-css) get their dark copy as they're added
    const mo = new MutationObserver((recs) => { for (const r of recs) for (const n of r.addedNodes) if (n.nodeType === 1 && (n.tagName === "LINK" || n.tagName === "STYLE")) companion(n); });
    mo.observe(document.documentElement, { childList: true, subtree: true });
    addEventListener("load", () => { mo.disconnect(); mo.observe(document.head, { childList: true }); }, { once: true });
    const hand = new URL("dark.css", KIT).href;
    if (write) document.write(`<link rel="stylesheet" href="${hand}" data-ydark="hand">`);
    else document.head.appendChild(mk(hand, "hand"));
    return Promise.all(pending);
  }
  // live switch (kit/components.html's Theme toggle): load first, then flip, so nothing paints half-themed
  async function set(m) {
    if (!VALUES.includes(m)) return;
    mode = m;
    if (m !== "light") await load();
    apply();
  }
  // a same-site link keeps ?theme while it isn't light (patched as it's used, so the page's own hrefs stay as built)
  function carry(e) {
    if (mode === "light") return;
    const a = e.target.closest?.("a[href]");
    if (!a || a.hasAttribute("download")) return;
    const raw = a.getAttribute("href");
    if (!raw || raw[0] === "#" || /^(mailto|tel|javascript|data|blob):/i.test(raw)) return;
    let u; try { u = new URL(raw, location.href); } catch (_) { return; }
    if (!u.href.startsWith(ROOT) || !/(\.html|\/)$/.test(u.pathname) || u.searchParams.has("theme")) return;
    u.searchParams.set("theme", mode);
    const same = u.origin === location.origin || u.protocol === "file:";
    a.setAttribute("href", same && u.protocol !== "file:" ? u.pathname + u.search + u.hash : u.href);
  }

  apply();
  if (mode !== "light") load({ write: SYNC });
  for (const t of ["pointerdown", "click", "auxclick", "keydown"]) addEventListener(t, carry, true);
  mq.addEventListener("change", () => { if (mode === "auto") apply(); });
  window.YarnTheme = { get mode() { return mode; }, get current() { return html.dataset.theme; }, set, after, load };
})();
